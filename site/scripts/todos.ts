// Collects every literal TODO marker in the site source into TODO.md, so no
// TODO can be hidden (brief §10). Runs before every build.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const scan = ["src", "astro.config.mjs", "public"];
const exts = /\.(ts|astro|mjs|md|mdx|csv|json)$/;
const re = /\[TODO:\s*([^\]]+)\]/g;

function walk(p: string): string[] {
  const st = statSync(p, { throwIfNoEntry: false });
  if (!st) return [];
  if (st.isDirectory()) return readdirSync(p).flatMap((f) => walk(join(p, f)));
  return exts.test(p) ? [p] : [];
}

const found = new Map<string, Set<string>>(); // todo text -> files
for (const file of scan.flatMap((s) => walk(join(root, s)))) {
  for (const m of readFileSync(file, "utf8").matchAll(re)) {
    const key = m[1].trim();
    if (!found.has(key)) found.set(key, new Set());
    found.get(key)!.add(relative(root, file));
  }
}

const lines = [
  "# TODO",
  "",
  "Auto-generated by `npm run todos` from every TODO marker in the source. Do not edit by hand:",
  "fix the fact in `src/content/content.ts` and the item disappears from here and from the site.",
  "",
  `**${found.size} open items**`,
  "",
  ...[...found].map(([t, files]) => `- [ ] ${t}  \n  <sub>${[...files].join(", ")}</sub>`),
  "",
];
writeFileSync(join(root, "TODO.md"), lines.join("\n"));
console.log(`TODO.md: ${found.size} open items`);
